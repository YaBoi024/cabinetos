// What the RomM client hands back: a platform, a collection, a game and its
// files, firmware, a save or a state, the person, a pairing in flight, a
// game's facts and a play session, and the two helpers that read a game
// (tagLabel, gameFromJson). A header that needs only these includes this file
// rather than the client (romm.h). Moved out of romm.h in the restructure
// (#398).
//
// A PLATFORM IS NOT ITS SLUG. RomM can hold several platforms with the same
// name AND the same slug: "Arcade" is the FBNeo, MAME, Naomi and Atomiswave
// folders in the reference library. Platform carries `id` as identity and
// `fsSlug`, the folder's name, as what a person tells them apart by. Never
// key on `slug` for identity.

#pragma once

#include <cstdint>
#include <string>
#include <vector>

namespace romm {

// A system, as RomM understands it. `id` is the ONLY unique field; see above.
struct Platform {
    int id = 0;
    std::string name;     // "Arcade" — not unique, and not always meaningful
    std::string slug;     // "arcade" — not unique either
    std::string fsSlug;   // "FBNEO" / "MAME2003" — what actually picks a core
    int romCount = 0;
    // THE TWO FIELDS A CACHE VALIDATES AGAINST, and they cost nothing because
    // the platform list is fetched at every boot anyway. `updatedAt` moves when
    // the platform changes; `romCount` catches the case where it does not.
    // Neither is used for anything else — see covercache and PROJECT.md 30.
    std::string updatedAt;
};

// A collection: the person's own grouping of games, held by RomM so it is the
// same on every device. Its games are fetched when it is opened, exactly as a
// platform's are (loadTileGames).
//
// RomM's own "Favorites" is a collection like any other, flagged `is_favorite`.
// Home already has a Favorites shelf fed by the favourites endpoint, so the
// Library deliberately shows it here too rather than hiding it: a person who
// opens Collections looking for the one they made is entitled to see the list
// their server actually holds.
//
// SMART COLLECTIONS (#352) are RomM's saved filters ("every GameCube game",
// "games with saves"): the server works out the members, and they come down
// in the same shape. Their ids are a separate count
// from regular collections' (both start at 1), so `smart` is part of what a
// collection is. RomM's autogenerated ("virtual") collections are left out
// on purpose: 115 franchise and genre groups on the reference server bury
// the collections people made, which is why RomM's own setting to show them
// is off there too (MMagTech, 2026-10-12).
//
// WHO SEES WHICH: RomM answers both lists with the caller's own collections
// and everyone's public ones (CollectionSchema.for_user), so a public
// collection a parent makes shows on a child's account and the parent's
// private ones do not. That holds because every account's library is loaded
// with that account's own token.
struct Collection {
    int id = 0;
    bool smart = false;
    int userId = 0;          // the owner; a public one may be somebody else's
    std::string ownerName;   // their RomM username, for "From <name>"
    std::string name;
    int romCount = 0;
    // A cover for the tile. RomM keeps a mosaic of member covers for a
    // collection with no art of its own, and the first of them is a real cover
    // from a real game inside it, which is all a tile needs.
    std::string coverPath;
    bool isFavorite = false;
};

// One file inside an archive, as RomM's `archive_members` lists it for a
// loose zip or 7z: its name, CRC32 and size. An arcade game's emulator is
// picked from these (arcadematch.h).
struct ArchiveMember {
    std::string name;
    uint32_t crc = 0;
    int64_t size = 0;
};

struct Game {
    int id = 0;
    int platformId = 0;
    // The ROM payload carries its own platform, so a game knows what it runs on
    // without a second lookup. Home needs this: the hero is the most recently
    // played game THIS CONSOLE CAN PLAY, which cannot be decided without it.
    std::string platformSlug;    // "dc"
    std::string platformFsSlug;  // "Sega Dreamcast"
    std::string platformName;    // "Dreamcast" — for the hero's band
    std::string name;
    std::string fsName;
    // RomM's own sort key ("The Bouncer" is "bouncer", digits padded): the
    // order the server returns a platform in, so the letter index has to
    // read its letters from this and not from the name.
    std::string sortKey;
    // Path on the server, not a URL: the cover fetch goes through the same
    // authenticated client, so callers hand this straight to ImageCache.
    //
    // TWO SIZES, AND THE SMALL ONE IS A THUMBNAIL. RomM keeps `small` at
    // 162x216 and `big` at 810x1080, for about double the bytes — the small
    // ones are inefficiently encoded PNGs, so 5x the pixels costs 1.5x the
    // transfer. Measured against the live server 2026-09-21.
    //
    // 162 points wide is not enough for anything on a 4K television: a shelf
    // cover is 158 design points, which is 316 real pixels, so even the
    // SMALLEST place art appears is a 2x upscale. Everywhere else is worse.
    // Ask for the size the drawing needs rather than the one that arrives
    // first — `coverLargePath` where a cover is big or full-screen, and the
    // thumbnail where it is a thumbnail.
    std::string coverPath;
    std::string coverLargePath;
    int64_t sizeBytes = 0;
    // RomM's `has_multiple_files` or `has_nested_single_file`: the game is a
    // folder (a .cue and its tracks, a Switch game with `update/` and `dlc/`,
    // one game file with `manual/` or `soundtrack/` beside it). RomM serves
    // a folder as a zip it makes, larger than `sizeBytes`, so it is fetched
    // file by file instead (launch_routes.cpp).
    bool multiFile = false;
    // RomM's `title_id`, as it sends it: hex, read off the file by RomM, or
    // by this console when RomM has none (romm_codes.cpp). Wii uses it to look
    // the game up in GameTDB's controller list (wii.h), GameCube for its
    // region (gameCubeRegion); empty for the many platforms with no ID.
    std::string titleId;
    // A Wii U game's product code, `BWPE`, read off its file by the console:
    // GameTDB's key for its controllers (wiiu.h). Empty for everything else.
    std::string productCode;
    // RomM's `ra_hash`: the fingerprint RetroAchievements knows this game by,
    // which RomM works out when it scans (#74). The console hands it over as
    // it is instead of reading the file itself, so a .chd disc needs no disc
    // reader here. Empty where RomM could not work one out.
    std::string raHash;
    // RomM's `md5_hash` of the game's file (inside its archive when it is
    // one): the Vectrex sheets' first key (vectrexsheets.h). Empty for none.
    std::string md5;
    // THE GAME'S MANUAL (#364): RomM's `path_manual`, a PDF in its resources,
    // `roms/1/2/manual/2.pdf`, served under /assets/romm/resources/. Filled
    // by the scraper or uploaded on the game's page; empty for none. The
    // extra documents in a game's own `manual` folder are never read.
    std::string manualPath;
    // RomM'S OWN READING OF THE BRACKETS IN THE FILE NAME (#383, PROJECT.md
    // question 48): `regions`, `languages`, `revision` and `tags`, as RomM
    // sends them, nothing worked out here. RomM documents this on its folder
    // structure page; whatever a library puts in brackets is what arrives.
    // `tagLabel` is the four joined for the heading, "(USA, Europe) (Rev 1)",
    // and empty when RomM sent none. RomM also reads a `version`, but does
    // not send it (rommapp/romm#5243).
    std::vector<std::string> regions;
    std::vector<std::string> languages;
    std::string revision;
    std::vector<std::string> tags;
    std::string tagLabel;
    // WHAT AN ARCADE GAME'S ARCHIVE HOLDS, kept in the game's record so its
    // emulator can be picked with no server (arcadematch.h): RomM's
    // `archive_members` for a loose zip or 7z, or what the console read off
    // one inside a folder game. `membersFile` and `membersSize` are the
    // archive they were read from, so a changed one is read again. Not in
    // RomM's lists; filled by a launch (launch_routes.cpp), in the record only.
    std::string membersFile;
    int64_t membersSize = 0;
    std::vector<ArchiveMember> members;
};

// RomM's four fields as one line, in RomM's order on its folder structure
// page: regions, languages, revision, then the other tags. Each group in its
// own brackets; empty when there are none.
std::string tagLabel(const Game& g);

// One BIOS file a platform carries.
//
// Cabinet's rule, and it is the right one: fetch EVERY file the platform lists
// rather than working out which one a given game needs. A core looks BIOS up by
// name in the system directory and ignores what it does not want — Beetle
// Saturn takes one of two region BIOSes, some FBNeo boards need none — so extra
// files are harmless and a missing one is the only failure that matters.
struct Firmware {
    int id = 0;
    std::string fileName;
    int64_t sizeBytes = 0;
};

// One file of a game, as RomM lists it under `files`. A game RomM holds as a
// folder (a PS3 PKG and its licence) is several; a one-file game is one.
//
// WHY A GAME WOULD BE FETCHED FILE BY FILE rather than as the one zip RomM
// makes of a folder: a PS3 PKG has to be installed after it arrives, and the
// zip route would hold the zip, the PKG unpacked from it and the installed
// game at once, three times a 20 GB game. File by file, it is twice, and only
// while the install runs. `?file_ids=` on the content endpoint serves one
// file as it is (RomM 5.3.1, checked 2026-09-28).
struct RomFile {
    int id = 0;
    std::string fileName;
    int64_t sizeBytes = 0;
    // RomM's `category` ("game", "manual", "dlc", ...; empty for a file at
    // the top of the folder on older servers) and `is_top_level`. A game on
    // several discs fetches only its own files (disc.h).
    std::string category;
    bool topLevel = true;
    // RomM's `archive_members`: what a loose zip or 7z holds. Empty for any
    // other file, and for an archive inside a folder game, which RomM does
    // not open.
    std::vector<ArchiveMember> members;
};

// A save or a save state held by RomM.
//
// They are separate endpoints and separate ideas, and Cabinet kept them apart
// on purpose. A SAVE is the game's own — a cartridge battery, a memory card —
// and it outlives everything; it is uploaded with overwrite so a PS1 game keeps
// one memory card rather than one per session. A STATE is a snapshot of the
// whole machine, only loadable by the build that wrote it, and a history of
// them is the point, so states never overwrite.
struct Asset {
    int id = 0;
    int romId = 0;          // the game it belongs to
    std::string fileName;
    int64_t sizeBytes = 0;
    // Which core wrote it. The reason states can be offered or greyed out
    // rather than failing in front of someone (docs/history/CABINET.md).
    std::string emulator;
    std::string updatedAt;
    // A state's picture on RomM (its `screenshot.download_path`), for the
    // launch screen. Empty for a save, or a state sent without one.
    std::string picturePath;
};

// Who the token belongs to.
//
// The console needs this before it writes a single save, because the on-disk
// layout is namespaced per user — `users/<id> - <name>/` — and RomM's own asset
// tree is namespaced the same way. The ID is the identity and the name is
// decoration: usernames change and ids do not, so a console keyed on the name
// would quietly start a new empty directory the day somebody renamed
// themselves, with every save still on the disk and nothing looking for it.
//
// The honest limit, recorded rather than solved: two RomM instances both have a
// User:1, and RomM exposes no instance identity to tell them apart. See
// docs/PROJECT.md, open questions 14 and 18.
struct User {
    int id = 0;
    std::string username;
    // RomM's `current_device_id`: the device this token is (#401).
    std::string deviceId;
    // The avatar, as a path this client can fetch, or empty when the person
    // never set one. NOT the `avatar_path` the server reports — that is a
    // location inside RomM's own asset tree ("users/<hash>/profile/<name>.png")
    // and it is not served anywhere underneath /assets, which is where every
    // other picture in this product comes from. Measured against the live
    // server 2026-09-21: all four spellings of that path are 404 and the file
    // is only reachable through `/api/users/<id>/avatar`, which answers a
    // 1200x1200 PNG. So the endpoint is what gets stored.
    std::string avatarPath;
};

// An in-flight pairing. Short-lived: RomM expires these in minutes.
struct Pairing {
    std::string userCode;          // shown to the person, e.g. "ZHVUCSF4"
    std::string verificationUrl;   // what the QR code encodes
    std::string deviceCode;        // secret; never shown, never logged
    int expiresIn = 0;
    int intervalSeconds = 5;
};

// A game's facts, as Client::fetchFacts hands them back (romm.h).
struct Facts {
    int year = 0;
    std::string maker;
    std::string players;   // as RomM gives it: "1", "1-2", "2"
    // The game's files, from the same payload: how the game page knows
    // a game is on several discs (disc.h).
    std::vector<RomFile> files;
};

// One play session, as Client::postPlaySessions sends it (romm.h).
struct PlaySession {
    int romId = 0;
    std::string start, end;   // ISO 8601, UTC
    int64_t durationMs = 0;
};

// A game read back from a record written in RomM's own field names (plus a
// Wii U game's `product_code`, the console's own): a keep record, or the
// console's note of a game it has on its drive. False when it is not one.
bool gameFromJson(const std::string& json, Game* out);

}  // namespace romm
